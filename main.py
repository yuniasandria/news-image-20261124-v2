def _glyph(font, ch):
    g = FONT[font].get(ord(ch))
    if g is None:
        g = FONT[font][63]
    return g


def text_width(font, s, scale=1):
    total = 0
    for ch in s:
        gw, _hx = _glyph(font, ch)
        total += gw + 1
    if total:
        total -= 1
    return total * scale


def draw_text(buf, x, y, s, font, scale, color):
    h = FONT_H[font]
    run = bytes(color) * scale
    cx = x
    for ch in s:
        gw, hx = _glyph(font, ch)
        raw = bytes.fromhex(hx)
        nb = (gw + 7) // 8
        for row in range(h):
            bits = int.from_bytes(raw[row * nb:(row + 1) * nb], "big")
            if not bits:
                continue
            yy = y + row * scale
            if yy < 0 or yy + scale > H:
                continue
            for col in range(gw):
                if (bits >> (gw - 1 - col)) & 1:
                    xx = cx + col * scale
                    if xx < 0 or xx + scale > W:
                        continue
                    base = (yy * W + xx) * 3
                    for dy in range(scale):
                        i = base + dy * W * 3
                        buf[i:i + 3 * scale] = run
        cx += (gw + 1) * scale
    return cx


def draw_center(buf, y, s, font, scale, color):
    x = (W - text_width(font, s, scale)) // 2
    draw_text(buf, x, y, s, font, scale, color)


def wrap(font, s, scale, maxw):
    lines = []
    cur = ""
    for wd in s.split(" "):
        trial = wd if not cur else cur + " " + wd
        if text_width(font, trial, scale) <= maxw or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = wd
    if cur:
        lines.append(cur)
    return lines


def rect(buf, x, y, w, h, color):
    row = bytes(color) * w
    for yy in range(y, y + h):
        i = (yy * W + x) * 3
        buf[i:i + w * 3] = row


def border(buf, x, y, w, h, color):
    rect(buf, x, y, w, 1, color)
    rect(buf, x, y + h - 1, w, 1, color)
    rect(buf, x, y, 1, h, color)
    rect(buf, x + w - 1, y, 1, h, color)


def write_png(buf, path):
    raw = b"".join(b"\x00" + bytes(buf[y * W * 3:(y + 1) * W * 3])
                   for y in range(H))
    comp = zlib.compress(raw, 6)

    def chunk(typ, data):
        c = struct.pack(">I", len(data)) + typ + data
        return c + struct.pack(">I", binascii.crc32(typ + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", comp)
    png += chunk(b"IEND", b"")
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    with open(path, "wb") as f:
        f.write(png)
    return len(png)


